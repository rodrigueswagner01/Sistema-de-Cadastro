    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed

        try {
            usuarioService.cadastrar(lerFormulario());
            carregarTabela();
            limparCampos();
        } catch (RuntimeException e) {
            tratarErro(e);
        }
    
    }//GEN-LAST:event_btnAdicionarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed

        int linha = tblUsuarios.getSelectedRow();

        if (linha >= 0) {
            try {
                usuarioService.excluir(listaUsuarios.get(linha).getId());
                carregarTabela();
                limparCampos();
            } catch (RuntimeException e) {
                tratarErro(e);
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um usuário.");
        }
    
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void tblUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsuariosMouseClicked

        int linha = tblUsuarios.getSelectedRow();

        if (linha >= 0) {
            Usuario u = listaUsuarios.get(linha);

            txtNome.setText(u.getNome());
            txtEmail.setText(u.getEmail());
            txtLogin.setText(u.getLogin());
            txtSenha.setText(u.getSenha());
            cbPerfil.setSelectedItem(u.getPerfil().getDescricao());
        }
    
    }//GEN-LAST:event_tblUsuariosMouseClicked

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed

        int linha = tblUsuarios.getSelectedRow();

        if (linha >= 0) {
            try {
                Usuario usuario = lerFormulario();
                usuario.setId(listaUsuarios.get(linha).getId());
                usuarioService.atualizar(usuario);
                carregarTabela();
                limparCampos();
            } catch (RuntimeException e) {
                tratarErro(e);
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um usuário para editar.");
        }
    
    }//GEN-LAST:event_btnEditarActionPerformed

