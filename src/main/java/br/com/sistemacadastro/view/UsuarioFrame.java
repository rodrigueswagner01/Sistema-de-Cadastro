 private void carregarTabela() {
    DefaultTableModel modelo = (DefaultTableModel) tblUsuarios.getModel();
    modelo.setRowCount(0);

    try {
        listaUsuarios = usuarioService.listarTodos();
    } catch (RuntimeException e) {
        tratarErro(e);
        return;
    }

    for (Usuario u : listaUsuarios) {
        modelo.addRow(new Object[]{
            u.getNome(),
            u.getEmail(),
            u.getLogin(),
            u.getSenha(),
            u.getPerfil()
        });
    }
}

    /** Converte os campos da tela em um Usuario (a validação das regras fica no service). */
    private Usuario lerFormulario() {
        PerfilUsuario perfil = PerfilUsuario.fromDescricao(cbPerfil.getSelectedItem().toString());
        return new Usuario(txtNome.getText(), txtEmail.getText(), perfil, txtLogin.getText(), txtSenha.getText());
    }

    private void tratarErro(RuntimeException e) {
        javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
    }
    
    private void limparCampos() {
    txtNome.setText("");
    txtEmail.setText("");
    txtLogin.setText("");
    txtSenha.setText("");
    cbPerfil.setSelectedIndex(0);
}
    
