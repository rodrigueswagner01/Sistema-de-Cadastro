private void carregarTabela() {
    DefaultTableModel modelo = (DefaultTableModel) tblProdutos.getModel();
    modelo.setRowCount(0);

    try {
        listaProdutos = produtoService.listarTodos();
    } catch (RuntimeException e) {
        tratarErro(e);
        return;
    }

    for (Produto p : listaProdutos) {
        modelo.addRow(new Object[]{
            p.getNome(),
            p.getDescricao(),
            p.getQuantidade(),
            p.getStatus()
        });
    }
}

    /** Converte os campos da tela em um Produto (a validação das regras fica no service). */
    private Produto lerFormulario() {
        int quantidade;
        try {
            quantidade = Integer.parseInt(txtQuantidade.getText().trim());
        } catch (NumberFormatException e) {
            throw new ValidacaoException("Informe uma quantidade válida (número inteiro).");
        }
        StatusProduto status = StatusProduto.fromDescricao(cbStatus.getSelectedItem().toString());
        return new Produto(txtNome.getText(), txtDescricao.getText(), quantidade, status);
    }

    private void tratarErro(RuntimeException e) {
        javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
    }
    
    private void limparCampos() {
    txtNome.setText("");
    txtDescricao.setText("");
    txtQuantidade.setText("");
    cbStatus.setSelectedIndex(0);
    }
