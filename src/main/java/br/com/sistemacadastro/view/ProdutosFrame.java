    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed

        int linha = tblProdutos.getSelectedRow();

        if (linha >= 0) {
            try {
                produtoService.excluir(listaProdutos.get(linha).getId());
                carregarTabela();
                limparCampos();
            } catch (RuntimeException e) {
                tratarErro(e);
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um produto.");
        }
    
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed

        int linha = tblProdutos.getSelectedRow();

        if (linha >= 0) {
            try {
                Produto produto = lerFormulario();
                produto.setId(listaProdutos.get(linha).getId());
                produtoService.atualizar(produto);
                carregarTabela();
                limparCampos();
            } catch (RuntimeException e) {
                tratarErro(e);
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um produto para atualizar.");
        }
    
    }//GEN-LAST:event_btnAtualizarActionPerformed

